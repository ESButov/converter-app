export const getRegionalBlocks = (
  species: RegionalSpeciesId,
  area: RegionalAreaId | 'all',
  navigation: RegionalNavigationId | 'all',
) => (
  regionalAnesthesiaBlocks.filter((block) => (
    block.species.includes(species)
    && (area === 'all' || block.area === area)
    && (navigation === 'all' || block.navigation.includes(navigation))
  ))
)

export const getRegionalBlockById = (id: string) => (
  regionalAnesthesiaBlocks.find((block) => block.id === id)
)
